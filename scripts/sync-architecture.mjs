#!/usr/bin/env node
/**
 * Sync the machine-generated "Codebase Map" section of ARCHITECTURE.md with the
 * actual code: backend modules, the HTTP route surface, and the external
 * shared-crate (rust-shared-utils) build mode (scaffold stub vs. real crate).
 *
 * Run automatically by the PostToolUse hook in `.claude/settings.json` after
 * Edit/Write/MultiEdit, or by hand:  node scripts/sync-architecture.mjs
 *
 * It ONLY rewrites the content between the AUTOGEN markers, and only when that
 * derived content actually changed — so prose/design sections and ordinary edit
 * noise are never touched. What a deterministic script CANNOT do is rewrite the
 * prose architecture to reflect a semantic change; when the code map changes it
 * prints a one-line reminder to review the prose.
 *
 * Design notes:
 * - Paths are resolved from THIS file's location, so cwd doesn't matter.
 * - Reads the hook's stdin JSON to (a) skip edits of the doc/script itself
 *   (loop-safety) and (b) no-op fast for edits outside server code.
 * - Never throws out to the caller: any error exits 0 so an edit is never
 *   blocked or failed by this hook.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, isAbsolute } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ARCH = join(ROOT, 'ARCHITECTURE.md');
const BEGIN =
  '<!-- BEGIN AUTOGEN: codebase-map (generated by scripts/sync-architecture.mjs — do not edit by hand) -->';
const END = '<!-- END AUTOGEN: codebase-map -->';

const read = (p) => readFileSync(join(ROOT, p), 'utf8');

/** The file that triggered the hook, if invoked as a PostToolUse hook. */
function triggeredFile() {
  if (process.stdin.isTTY) return null; // manual run: no hook payload
  try {
    const raw = readFileSync(0, 'utf8'); // fd 0 = stdin
    if (!raw.trim()) return null;
    const j = JSON.parse(raw);
    return j?.tool_input?.file_path || j?.tool_input?.path || null;
  } catch {
    return null;
  }
}

try {
  const trigger = triggeredFile();

  // Scope: regenerate only when something that feeds the map changed — server
  // code, the dependency manifest, the stubs, or THIS generator itself (so a
  // change to the generator logic is reflected immediately). If the trigger is
  // known and outside these, no-op fast. ARCHITECTURE.md is deliberately NOT in
  // scope, so a doc edit never self-regenerates; and a hook's own child-process
  // file writes do not re-fire PostToolUse, so there is no recursion to guard
  // against. `file_path` may be absolute or relative-to-root — normalize either.
  if (trigger) {
    const abs = isAbsolute(trigger) ? trigger : join(ROOT, trigger);
    // Normalize to forward slashes so checks work on Windows too, where
    // path.relative() yields backslash-separated paths (this repo supports Win).
    const rel = relative(ROOT, abs).replace(/\\/g, '/');
    const relevant =
      rel.startsWith('server/src/') ||
      rel === 'server/Cargo.toml' ||
      rel.startsWith('server/stubs/') ||
      rel === 'scripts/sync-architecture.mjs';
    if (!relevant) process.exit(0);
  }

  // --- Backend modules (server/src/lib.rs) ---
  const modules = [...read('server/src/lib.rs').matchAll(/^pub mod (\w+);/gm)]
    .map((m) => m[1])
    .sort();

  // --- HTTP route surface: every `.route("...")` across server/src, so routes
  //     contributed by merged sub-routers (e.g. `agent::router()`, which the
  //     top-level router `.merge()`s) are counted too, not just router.rs. The
  //     `\s*` in the regex spans newlines, so multi-line `.route(` calls match. ---
  const srcDir = join(ROOT, 'server/src');
  const rsFiles = readdirSync(srcDir, { recursive: true }).filter(
    (f) => typeof f === 'string' && f.endsWith('.rs'),
  );
  const routePaths = [];
  for (const rf of rsFiles) {
    const txt = readFileSync(join(srcDir, rf), 'utf8');
    for (const m of txt.matchAll(/\.route\(\s*"([^"]+)"/g)) routePaths.push(m[1]);
  }
  const groups = {};
  for (const p of routePaths) {
    const seg = p.split('/').filter(Boolean)[0] || '(root)';
    groups[seg] = (groups[seg] || 0) + 1;
  }
  const groupList = Object.entries(groups).sort((a, b) => a[0].localeCompare(b[0]));

  // --- External shared-crate build mode (server/Cargo.toml) ---
  const cargo = read('server/Cargo.toml').split('\n');
  const SHARED = ['pipeline', 'pg', 'app-config', 'rcl', 'cdc', 'secret_manager'];
  const depStatus = SHARED.map((name) => {
    const re = new RegExp(`^${name.replace(/[-]/g, '\\-')}\\s*=`);
    const line = cargo.find((l) => !l.trim().startsWith('#') && re.test(l.trim()));
    let mode = 'unknown';
    if (line) {
      if (/path\s*=\s*"stubs\//.test(line)) mode = 'stub (path)';
      else if (/git\s*=\s*"ssh/.test(line)) mode = 'real (git/ssh)';
    }
    return { name, mode };
  });
  const allStub = depStatus.every((d) => d.mode === 'stub (path)');

  // --- Render the section ---
  const L = [];
  L.push(BEGIN, '');
  L.push(
    '_Auto-generated from the code by `scripts/sync-architecture.mjs` (run by a PostToolUse hook). Do not edit by hand — edit the code or the script. The prose sections above are maintained manually._',
    '',
  );
  L.push(`### Backend modules (\`server/src/\`) — ${modules.length}`, '');
  L.push(modules.map((m) => `\`${m}\``).join(' · '), '');
  L.push(
    `### HTTP API surface (all \`server/src\` routers) — ${routePaths.length} routes across ${groupList.length} groups`,
    '',
  );
  L.push('| Route group | Routes |', '|---|---|');
  for (const [g, n] of groupList) L.push(`| \`/${g}\` | ${n} |`);
  L.push('');
  L.push('### External shared-crate dependencies (`rust-shared-utils`)', '');
  L.push('| Crate | Build mode |', '|---|---|');
  for (const d of depStatus) L.push(`| \`${d.name}\` | ${d.mode} |`);
  L.push('');
  L.push(
    allStub
      ? 'All six resolve to **stub (path)** — the repo builds with no SSH/Bitbucket access and no proprietary code; features backed by these crates are inert. See `server/stubs/README.md`.'
      : '**Mixed/real mode** — one or more crates build from the private `rust-shared-utils` repo, which requires SSH/Bitbucket access. See `server/stubs/README.md` to switch back to the stub build.',
  );
  L.push('', END);
  const section = L.join('\n');

  // --- Splice into ARCHITECTURE.md (only if changed) ---
  const doc = read('ARCHITECTURE.md');
  const bi = doc.indexOf(BEGIN);
  const ei = doc.indexOf(END);
  if (bi === -1 || ei === -1) {
    console.error('[sync-architecture] AUTOGEN markers not found in ARCHITECTURE.md — skipped.');
    process.exit(0);
  }
  const next = doc.slice(0, bi) + section + doc.slice(ei + END.length);
  if (next === doc) process.exit(0); // no change — stay quiet

  writeFileSync(ARCH, next);
  console.log(
    '[sync-architecture] ARCHITECTURE.md codebase map updated (modules/routes/deps changed). Review the prose sections if this was a structural change.',
  );
} catch (err) {
  // Never block or fail an edit because of this hook.
  console.error(`[sync-architecture] skipped: ${err?.message ?? err}`);
  process.exit(0);
}
